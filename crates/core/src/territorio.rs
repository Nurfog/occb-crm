/// Busca una región por su código.
pub fn region(codigo: u8) -> Option<Region> {
    REGIONES.iter().find(|r| r.codigo == codigo).copied()
}

/// Todas las comunas de una región, ordenadas por nombre.
pub fn comunas_de_region(codigo: u8) -> Vec<Comuna> {
    let mut lista: Vec<Comuna> = COMUNAS.iter().filter(|c| c.region == codigo).copied().collect();
    lista.sort_by(|a, b| a.nombre.cmp(b.nombre));
    lista
}

/// Busca una comuna por su CUT.
pub fn comuna_por_cut(cut: &str) -> Option<Comuna> {
    COMUNAS.iter().find(|c| c.cut == cut).copied()
}

/// Valida una pareja región/comuna para formularios y API.
/// Acepta ambas ausentes; si hay comuna, exige región coincidente y códigos existentes.
pub fn validar_territorio(region_codigo: Option<u8>, comuna: Option<&str>) -> Result<(), crate::ErrorDominio> {
    match (region_codigo, comuna) {
        (None, None) => Ok(()),
        (Some(r), None) => region(r)
            .map(|_| ())
            .ok_or_else(|| crate::ErrorDominio::Validacion("La región no es válida.".into())),
        (None, Some(_)) => Err(crate::ErrorDominio::Validacion(
            "Elija primero la región para validar la comuna.".into(),
        )),
        (Some(r), Some(cut)) => match comuna_por_cut(cut) {
            Some(c) if c.region == r => Ok(()),
            Some(_) => Err(crate::ErrorDominio::Validacion(
                "La comuna no pertenece a la región elegida.".into(),
            )),
            None => Err(crate::ErrorDominio::Validacion("La comuna no es válida.".into())),
        },
    }
}

